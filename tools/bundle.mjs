// Packs a board's guides and prep sheets into Library/_bundle.js, a plain script the page loads.
// The page reads the Markdown files live once saving is on; the bundle lets it show them before that
// (and in browsers that can't read folders). Run it after you add or change a guide by hand:
//
//   node tools/bundle.mjs <board folder>           write Library/_bundle.js
//   node tools/bundle.mjs <board folder> --check   fail if it is out of date
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";

const board = resolve(process.argv[2] || ".");
const check = process.argv.includes("--check");
const files = {};
const skip = (name) =>
  name === "README.md" || name === "My_answers.md" || name.startsWith("_") || !name.endsWith(".md");
const addIf = (rel) => {
  const p = join(board, rel);
  if (existsSync(p) && statSync(p).isFile()) files[rel] = readFileSync(p, "utf8");
};
const list = (rel) => (existsSync(join(board, rel)) ? readdirSync(join(board, rel), { withFileTypes: true }) : []);

// Library/*.md and Library/<group>/*.md, except README.md, your own answers and files starting with "_"
for (const e of list("Library")) {
  if (e.isFile() && !skip(e.name)) addIf(`Library/${e.name}`);
  if (e.isDirectory())
    for (const f of list(`Library/${e.name}`)) if (f.isFile() && !skip(f.name)) addIf(`Library/${e.name}/${f.name}`);
}
// Job notes/<job id>/{prep,outreach,posting}.md (never my_notes.md: those are yours and only the page writes them)
for (const e of list("Job notes")) {
  if (!e.isDirectory() || e.name === "hunters") continue;
  for (const n of ["prep", "outreach", "posting"]) addIf(`Job notes/${e.name}/${n}.md`);
}
const sorted = Object.fromEntries(
  Object.keys(files)
    .sort()
    .map((k) => [k, files[k]]),
);
const text =
  "// Generated by tools/bundle.mjs from the Markdown files in Library and Job notes. Edit those files, not this one.\n" +
  "window.ORGANIZER_LIBRARY = " +
  JSON.stringify({ files: sorted }, null, 1).replace(/<\//g, "<\\/") +
  ";\n";
const out = join(board, "Library", "_bundle.js");
if (check) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error(`out of date: ${out} (run npm run bundle)`);
    process.exit(1);
  }
  console.log(`up to date: ${out}`);
} else {
  mkdirSync(join(board, "Library"), { recursive: true });
  writeFileSync(out, text);
  console.log(`bundled ${Object.keys(sorted).length} files into ${out}`);
}
